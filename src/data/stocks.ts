// Add health indicators to all stocks
export const stocks: Stock[] = rawStocks.map(stock => ({
  ...stock,
  health: calculateStockHealth(stock as Stock),
}));

// Get stock by ID/ticker
export function getStockById(id: string): Stock | undefined {
  return stocks.find(s => s.id.toLowerCase() === id.toLowerCase() || s.ticker.toLowerCase() === id.toLowerCase());
}

// Search stocks by name or ticker
export function searchStocks(query: string): Stock[] {
  const lowerQuery = query.toLowerCase().trim();
  if (!lowerQuery) return [];
  
  return stocks.filter(stock => 
    stock.ticker.toLowerCase().includes(lowerQuery) ||
    stock.name.toLowerCase().includes(lowerQuery) ||
    stock.sector.toLowerCase().includes(lowerQuery)
  );
}

// Get stocks by sector
export function getStocksBySector(sector: string): Stock[] {
  return stocks.filter(stock => stock.sector.toLowerCase() === sector.toLowerCase());
}

// Get unique sectors
export function getSectors(): string[] {
  return [...new Set(stocks.map(s => s.sector))].sort();
}

// Get popular stocks (top by market cap)
export function getPopularStocks(limit = 10): Stock[] {
  return [...stocks].sort((a, b) => b.marketCap - a.marketCap).slice(0, limit);
}
